export function emptyAdminDeletionWhere(userId:string,email:string):Prisma.UserWhereInput {
  // A new relation is a negative restriction until reviewed explicitly.
  const names=Prisma.dmmf.datamodel.models.find(m=>m.name==='User')?.fields.filter(f=>f.kind==='object').map(f=>f.name).sort();
  if(!names||JSON.stringify(names)!==JSON.stringify(Object.keys(emptyRelations).sort()))throw Error('Admin user deletion unconfirmed');
  return { id:userId,email,referralCode:null,referredBy:null,referredByCode:null,referralRewardedAt:null,...emptyRelations };
}
